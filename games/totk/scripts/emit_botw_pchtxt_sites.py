#!/usr/bin/env python3
"""Generate the launch-time reserved ranges from the build-time source reader.

--version botw (the default) writes runtime/botw_pchtxt_sites.h for Breath of the Wild 1.9.0 and 1.6.0;
--version v143 writes runtime/v143_pchtxt_sites.h for TOTK 1.4.3 (the sites patch_sites.py reserves for the build's --mod)."""
import argparse
from pathlib import Path
from patch_sites import sites

# TOTK 1.4.3 main's NSO build ID (the 16 bytes the rewriter's tables in third_party/d2r/patch_nso.py are keyed on): with it,
# sites() also reserves that build's cuts, observation gates, parameters and signed jump tables, as the build's --mod does.
V143_BUILD_ID = '277178b7dba1b6d4949a84778d4abc58'


def render_v143():
    lines = ['/* Generated by scripts/emit_botw_pchtxt_sites.py --version v143; do not edit the offsets by hand. */',
             '#pragma once', 'static const PchtxtSite g_pchtxt_reserved[] = {']
    lines.extend(f'    {{0x{site.offset:x}, 0x{site.size:x}}},' for site in sites('v143', V143_BUILD_ID))   # sorted and unique
    lines += ['};', '']
    return '\n'.join(lines)


def render():
    lines = ['/* Generated by scripts/emit_botw_pchtxt_sites.py; do not edit the offsets by hand. */',
             '#pragma once', 'static const PchtxtSite g_pchtxt_reserved[] = {']
    for version, guard in [('botw190', '#ifdef GAME_BOTW190'), ('botw160', '#else')]:
        lines.append(guard)
        # The account GOT slot is a pointer, while the address reader reserves its instruction-sized first word.
        ranges = {(s.offset, s.size) for s in sites(version)}
        got = 0x1d78198 if version == 'botw190' else 0x2c7ef90
        ranges.discard((got, 4)); ranges.add((got, 8))
        lines.extend(f'    {{0x{offset:x}, 0x{size:x}}},' for offset, size in sorted(ranges))
    lines += ['#endif', '};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--version', choices=('botw', 'v143'), default='botw')
    args = parser.parse_args()
    text = render_v143() if args.version == 'v143' else render()
    if not args.out.exists() or args.out.read_text() != text:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
